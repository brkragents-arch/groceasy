function createProduct(
  data: Omit<Product, 'ingredients' | 'rawIngredientsText' | 'safetyAssessment' | 'isDemonstrationData' | 'dataSource' | 'lastUpdated'> & { rawIngredients: string },
  _photoIndex?: number
): Product {
  const analyzedIngredients = analyzeIngredientText(data.rawIngredients);
  const safetyAssessment = calculateSafetyScore(
    data.category,
    analyzedIngredients,
    data.nutritionFacts,
    data.skinSuitability,
    { name: data.name, subcategory: data.subcategory, brand: data.brand, rawIngredients: data.rawIngredients }
  );

  // Exact 1-to-1 matching Amazon product listing image
  const amazonPhoto = (exactAmazonProductPhotos as Record<string, string>)[data.id] || data.thumbnailUrl;

  return {
    ...data,
    thumbnailUrl: amazonPhoto,
    ingredients: analyzedIngredients,
    rawIngredientsText: data.rawIngredients,
    safetyAssessment,
    isDemonstrationData: true,
    dataSource: 'Amazon India Direct Catalog (FSSAI / BIS IS:4707 Evaluated)',
    lastUpdated: '2026-10-17'
  };
}

